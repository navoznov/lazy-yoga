// Downloads yoga_api pose SVGs into public/icons/ and generates src/poses/icons.ts.
// Run: npx tsx scripts/fetch-icons.ts
import { mkdir, writeFile } from 'node:fs/promises'

const API_URL = 'https://raw.githubusercontent.com/rebeccaestes/yoga_api/master/yoga_api.json'
const ICONS_DIR = 'public/icons'
const OUT_FILE = 'src/poses/icons.ts'

const CREDITS = [
  { author: 'Claire Jones', source: 'https://thenounproject.com/hivernoir/collection/yoga/', license: 'CC BY 3.0 (unverified — user to confirm)' },
  { author: 'Elizabeth Sobka', source: 'https://thenounproject.com/southofbelmar/', license: 'CC BY 3.0 (unverified — user to confirm)' },
  { author: 'yoga_api (Rebecca Estes)', source: 'https://github.com/rebeccaestes/yoga_api', license: 'no license stated (pose list only)' },
]

interface ApiPose {
  english_name: string
  img_url: string
}

function toKey(englishName: string): string {
  return englishName
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function candidateUrls(imgUrl: string): string[] {
  const url = new URL(imgUrl)
  const dl = new URL(url)
  dl.searchParams.set('dl', '1')
  dl.searchParams.delete('raw')
  const direct = new URL(url)
  direct.hostname = 'dl.dropboxusercontent.com'
  direct.search = ''
  return [url.href, dl.href, direct.href]
}

async function downloadSvg(imgUrl: string): Promise<string> {
  const errors: string[] = []
  for (const url of candidateUrls(imgUrl)) {
    try {
      const res = await fetch(url)
      const text = await res.text()
      if (!res.ok) throw new Error(`HTTP ${res.status}`)
      if (!/^<(svg|\?xml)/.test(text.trimStart())) throw new Error('not an SVG')
      return text
    } catch (e) {
      errors.push(`${url}: ${(e as Error).message}`)
    }
  }
  throw new Error(errors.join('; '))
}

async function main(): Promise<void> {
  const poses = (await (await fetch(API_URL)).json()) as ApiPose[]
  await mkdir(ICONS_DIR, { recursive: true })

  const keys: string[] = []
  for (const pose of poses) {
    const key = toKey(pose.english_name)
    if (keys.includes(key)) {
      console.warn(`skip ${pose.english_name}: duplicate key ${key}`)
      continue
    }
    try {
      await writeFile(`${ICONS_DIR}/${key}.svg`, await downloadSvg(pose.img_url))
      keys.push(key)
      console.log(`ok   ${key}`)
    } catch (e) {
      console.warn(`skip ${key}: ${(e as Error).message}`)
    }
  }

  const source = `// Generated by scripts/fetch-icons.ts — do not edit by hand.
// Icon URL: \`\${import.meta.env.BASE_URL}icons/\${key}.svg\`

export const ICON_KEYS: readonly string[] = ${JSON.stringify(keys, null, 2)}

export const ICON_CREDITS: { author: string; source: string; license: string }[] = ${JSON.stringify(CREDITS, null, 2)}
`
  await writeFile(OUT_FILE, source)
  console.log(`\n${keys.length}/${poses.length} icons written`)
}

await main()
